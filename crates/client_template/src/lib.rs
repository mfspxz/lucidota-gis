//! client_template — gis-015: reusable client GIS crate generator.
//!
//! Given a client name, region bbox, and places, scaffolds a ready-to-build
//! crate (dataset + layers + validation + tests) that depends only on geo_core.

#[derive(Debug, Clone)]
pub struct ClientPlace {
    pub name: String,
    pub kind: String,
    pub lat: f64,
    pub lon: f64,
    pub note: String,
}

#[derive(Debug, Clone)]
pub struct ClientSpec {
    pub client: String,      // e.g. "harbour-air-tours"
    pub region_name: String, // e.g. "victoria-harbour"
    pub min_lat: f64, pub max_lat: f64, pub min_lon: f64, pub max_lon: f64,
    pub places: Vec<ClientPlace>,
}

fn slug(s: &str) -> String {
    s.to_lowercase().chars().map(|c| if c.is_alphanumeric() { c } else { '_' }).collect()
}

fn esc(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

/// Scaffold the client crate into out_dir. Returns the crate dir path.
pub fn generate(spec: &ClientSpec, out_dir: &str) -> std::io::Result<String> {
    let crate_name = slug(&spec.client);
    let dir = format!("{out_dir}/{crate_name}");
    std::fs::create_dir_all(format!("{dir}/src"))?;
    std::fs::create_dir_all(format!("{dir}/tests"))?;

    let geo_core_path = format!("{}/../geo_core", env!("CARGO_MANIFEST_DIR"));
    let cargo = format!(
        "[package]\nname = \"{crate_name}\"\nversion = \"0.1.0\"\nedition = \"2024\"\n\n[dependencies]\ngeo_core = {{ path = \"{geo_core_path}\" }}\n"
    );
    std::fs::write(format!("{dir}/Cargo.toml"), cargo)?;

    let mut places_rs = String::new();
    for p in &spec.places {
        places_rs.push_str(&format!(
            "        Place {{ name: \"{}\", kind: \"{}\", pos: LatLon::new_unchecked({:.6}, {:.6}), note: \"{}\" }},\n",
            esc(&p.name), esc(&p.kind), p.lat, p.lon, esc(&p.note)
        ));
    }
    let lib = format!(
        r#"//! {client} GIS dataset (generated by client_template).
use geo_core::coord::LatLon;
use geo_core::geojson::{{Feature, FeatureCollection, Geometry}};
use geo_core::validate::Region;

pub struct Place {{
    pub name: &'static str,
    pub kind: &'static str,
    pub pos: LatLon,
    pub note: &'static str,
}}

pub fn region() -> Region {{
    Region {{
        name: "{region}".into(),
        min_lat: {min_lat:.6}, max_lat: {max_lat:.6},
        min_lon: {min_lon:.6}, max_lon: {max_lon:.6},
    }}
}}

pub fn places() -> Vec<Place> {{
    vec![
{places}    ]
}}

pub fn layers_geojson() -> Vec<(String, String)> {{
    let mut fc = FeatureCollection::new();
    for pl in places() {{
        fc.push(
            Feature::new(Geometry::Point(pl.pos))
                .prop("name", pl.name)
                .prop("kind", pl.kind)
                .prop("note", pl.note),
        );
    }}
    vec![("places".into(), fc.to_json())]
}}

pub fn validate_all() -> Vec<String> {{
    let r = region();
    let mut errs = Vec::new();
    for pl in places() {{
        if let geo_core::validate::Verdict::Reject(msg) = r.check_point(&pl.pos) {{
            errs.push(format!("place {{}}: {{msg}}", pl.name));
        }}
    }}
    errs
}}
"#,
        client = spec.client, region = spec.region_name,
        min_lat = spec.min_lat, max_lat = spec.max_lat,
        min_lon = spec.min_lon, max_lon = spec.max_lon, places = places_rs
    );
    std::fs::write(format!("{dir}/src/lib.rs"), lib)?;

    let test = r#"use client_gen_check::{validate_all, layers_geojson, places};

#[test]
fn generated_crate_validates() {
    assert!(validate_all().is_empty());
    assert!(!places().is_empty());
    let layers = layers_geojson();
    assert!(layers[0].1.contains("\"type\":\"FeatureCollection\""));
}
"#;
    // the test refers to the crate by its real name; rewrite the use line
    let test = test.replace("client_gen_check", &crate_name);
    std::fs::write(format!("{dir}/tests/gen.rs"), test)?;
    Ok(dir)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn demo_spec() -> ClientSpec {
        ClientSpec {
            client: "Demo Marina".into(),
            region_name: "demo-harbour".into(),
            min_lat: 48.40, max_lat: 48.50, min_lon: -123.45, max_lon: -123.30,
            places: vec![
                ClientPlace { name: "Demo Dock".into(), kind: "dock".into(), lat: 48.45, lon: -123.38, note: "main dock".into() },
                ClientPlace { name: "Fuel".into(), kind: "fuel".into(), lat: 48.44, lon: -123.36, note: "diesel".into() },
            ],
        }
    }

    #[test]
    fn template_scaffolds_expected_files() {
        let out = "/tmp/client_template_test";
        let _ = std::fs::remove_dir_all(out);
        let dir = generate(&demo_spec(), out).unwrap();
        for f in ["Cargo.toml", "src/lib.rs", "tests/gen.rs"] {
            assert!(std::path::Path::new(&format!("{dir}/{f}")).exists(), "missing {f}");
        }
        let lib = std::fs::read_to_string(format!("{dir}/src/lib.rs")).unwrap();
        assert!(lib.contains("demo-harbour"));
        assert!(lib.contains("Demo Dock"));
    }

    #[test]
    fn generated_crate_builds_and_passes_its_tests() {
        // Honest proof: the scaffolded crate is a real, compiling, tested crate.
        let out = "/tmp/client_template_build";
        let _ = std::fs::remove_dir_all(out);
        let dir = generate(&demo_spec(), out).unwrap();
        let o = std::process::Command::new("/home/hatch/.cargo/bin/cargo")
            .args(["test", "--offline", "--quiet"])
            .current_dir(&dir)
            .output()
            .expect("cargo spawn");
        assert!(o.status.success(), "generated crate tests failed:\n{}", String::from_utf8_lossy(&o.stderr));
    }
}
